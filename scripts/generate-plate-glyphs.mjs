import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import opentype from 'opentype.js';

// Display alphabet of RU plates: digits + Latin look-alikes used by toDisplayLatin().
const CHARS = '0123456789ABEKMHOPTCYX';

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const fontPath = path.join(root, 'scripts', 'RoadNumbers2.0.ttf');
const outPath = path.join(root, 'src', 'features', 'plates', 'ui', 'plateGlyphs.generated.ts');

const buffer = fs.readFileSync(fontPath);
const font = opentype.parse(
  buffer.buffer.slice(buffer.byteOffset, buffer.byteOffset + buffer.byteLength),
);

const round = (value) => Number(value.toFixed(2));

const glyphs = {};
let minX = Infinity;
let minY = Infinity;
let maxX = -Infinity;
let maxY = -Infinity;

for (const char of CHARS) {
  const glyph = font.charToGlyph(char);
  const pathData = glyph.getPath(0, 0, font.unitsPerEm);
  const bbox = pathData.getBoundingBox();
  minX = Math.min(minX, bbox.x1);
  minY = Math.min(minY, bbox.y1);
  maxX = Math.max(maxX, bbox.x2);
  maxY = Math.max(maxY, bbox.y2);
  glyphs[char] = { d: pathData.toPathData(2), advance: round(glyph.advanceWidth) };
}

// Glyphs render baseline-anchored (y-down, baseline at y=0); the union box is the
// shared viewBox height so every glyph scales identically.
const bounds = { minX: round(minX), minY: round(minY), maxX: round(maxX), maxY: round(maxY) };
const scale = (bounds.maxY - bounds.minY) / font.unitsPerEm;

const lines = [
  '// Generated by scripts/generate-plate-glyphs.mjs from scripts/RoadNumbers2.0.ttf — do not edit.',
  '',
  'export interface PlateGlyph {',
  '  d: string;',
  '  advance: number;',
  '}',
  '',
  `export const PLATE_FONT_SCALE = ${scale};`,
  '',
  `export const PLATE_GLYPH_BOUNDS = ${JSON.stringify(bounds)};`,
  '',
  'export const PLATE_GLYPHS: Record<string, PlateGlyph> = {',
  ...Object.entries(glyphs).map(
    ([char, glyph]) => `  '${char}': { d: '${glyph.d}', advance: ${glyph.advance} },`,
  ),
  '};',
  '',
];

fs.writeFileSync(outPath, lines.join('\n'));
console.log(
  `plateGlyphs.generated.ts: ${Object.keys(glyphs).length} glyphs, bounds ${JSON.stringify(bounds)}, scale ${scale}`,
);
